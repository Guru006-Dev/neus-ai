import type { AgentOutput } from '../data/types'
import { RawOutput } from './RawOutput'
import { Showcase } from './Showcase'

export function DemoOutput({ output, runId }: { output: Extract<AgentOutput, { agent: 'demo' }>; runId: string }) {
  return (
    <div className="nx-out">
      <dl className="nx-dl">
        <div><dt>Generator</dt><dd>{output.generatedBy === 'gemini-llm' ? 'Generated by Gemini' : 'Generated by fallback engine'}</dd></div>
        {output.status && <div><dt>Status</dt><dd>{output.status}</dd></div>}
        {output.lineCount !== undefined && <div><dt>Lines</dt><dd>{output.lineCount}</dd></div>}
      </dl>
      <Showcase runId={runId} kind="demo_html" title="Demo showcase" />
      <RawOutput raw={output.raw} />
    </div>
  )
}
